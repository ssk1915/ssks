-- ========================================================
-- TravelMates (친구와 여행 모임) Database Schema for MySQL
-- Rule: 테이블명, 컬럼명 모두 대문자(UPPERCASE) 표기
-- ========================================================

CREATE DATABASE IF NOT EXISTS TRAVELMATES_DB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE TRAVELMATES_DB;

-- 기존 테이블 삭제 (외래키 제약조건 역순)
DROP TABLE IF EXISTS EXPENSE_PARTICIPANT;
DROP TABLE IF EXISTS EXPENSE_SETTLEMENT;
DROP TABLE IF EXISTS TRIP_GALLERY;
DROP TABLE IF EXISTS TRIP_SCHEDULE;
DROP TABLE IF EXISTS TRIP_MEMBER;
DROP TABLE IF EXISTS TRIP_GROUP;
DROP TABLE IF EXISTS MEMBER;

-- 1. 회원 테이블 (MEMBER)
CREATE TABLE MEMBER (
    MEMBER_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '회원 고유 식별자',
    USERNAME VARCHAR(50) NOT NULL UNIQUE COMMENT '로그인 아이디',
    PASSWORD VARCHAR(255) NOT NULL COMMENT '암호화된 비밀번호',
    NAME VARCHAR(50) NOT NULL COMMENT '회원 이름/닉네임',
    EMAIL VARCHAR(100) NOT NULL UNIQUE COMMENT '이메일 주소',
    PHONE VARCHAR(255) NULL COMMENT '암호화된 전화번호',
    PROFILE_IMAGE VARCHAR(255) NULL COMMENT '프로필 이미지 URL',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='회원 정보 테이블';

-- 2. 여행 모임 테이블 (TRIP_GROUP)
CREATE TABLE TRIP_GROUP (
    GROUP_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '모임 고유 식별자',
    GROUP_NAME VARCHAR(100) NOT NULL COMMENT '모임명',
    TRIP_TYPE ENUM('국내', '해외') NOT NULL DEFAULT '국내' COMMENT '여행 구분 (국내/해외)',
    LOCATION VARCHAR(100) NOT NULL COMMENT '여행 목적지 (예: 제주도, 방콕)',
    START_DATE DATE NOT NULL COMMENT '여행 시작일',
    END_DATE DATE NOT NULL COMMENT '여행 종료일',
    MAX_MEMBERS INT NOT NULL DEFAULT 4 COMMENT '최대 모집 인원',
    ESTIMATED_BUDGET VARCHAR(50) NULL COMMENT '예상 1인 예산',
    DESCRIPTION TEXT NULL COMMENT '모임 상세 설명 및 테마',
    IMAGE_URL VARCHAR(255) NULL COMMENT '대표 커버 이미지 URL',
    STATUS ENUM('RECRUITING', 'COMPLETED', 'CANCELLED') DEFAULT 'RECRUITING' COMMENT '모집 상태',
    CREATED_BY INT NOT NULL COMMENT '개설자 회원 ID',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    FOREIGN KEY (CREATED_BY) REFERENCES MEMBER(MEMBER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='여행 모임 정보 테이블';

-- 3. 모임 참여 멤버 매핑 테이블 (TRIP_MEMBER)
CREATE TABLE TRIP_MEMBER (
    TRIP_MEMBER_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '참여 매핑 ID',
    GROUP_ID INT NOT NULL COMMENT '모임 ID',
    MEMBER_ID INT NOT NULL COMMENT '회원 ID',
    ROLE ENUM('LEADER', 'MEMBER') DEFAULT 'MEMBER' COMMENT '모임 내 역할',
    JOINED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '참여일시',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    UNIQUE KEY UQ_GROUP_MEMBER (GROUP_ID, MEMBER_ID),
    FOREIGN KEY (GROUP_ID) REFERENCES TRIP_GROUP(GROUP_ID) ON DELETE CASCADE,
    FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER(MEMBER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='모임 참여 회원 테이블';

-- 4. 여행 일정 타임라인 테이블 (TRIP_SCHEDULE)
CREATE TABLE TRIP_SCHEDULE (
    SCHEDULE_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '일정 고유 식별자',
    GROUP_ID INT NOT NULL COMMENT '모임 ID',
    DAY_NUMBER INT NOT NULL DEFAULT 1 COMMENT '일차 (Day 1, Day 2...)',
    PLAN_TIME VARCHAR(50) NOT NULL COMMENT '시간대 (예: 10:30, 점심)',
    PLACE VARCHAR(100) NOT NULL COMMENT '장소 및 활동명',
    MEMO TEXT NULL COMMENT '준비물 및 세부 메모',
    LATITUDE DECIMAL(10, 7) NULL COMMENT '위도 좌표',
    LONGITUDE DECIMAL(10, 7) NULL COMMENT '경도 좌표',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    FOREIGN KEY (GROUP_ID) REFERENCES TRIP_GROUP(GROUP_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='여행 일정 타임라인 테이블';

-- 5. 지출 정산 영수증 테이블 (EXPENSE_SETTLEMENT)
CREATE TABLE EXPENSE_SETTLEMENT (
    SETTLEMENT_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '지출 고유 식별자',
    GROUP_ID INT NOT NULL COMMENT '모임 ID',
    PAYER_ID INT NOT NULL COMMENT '선결제한 회원 ID',
    TITLE VARCHAR(100) NOT NULL COMMENT '지출 항목명 (예: 첫날 흑돼지 저녁)',
    EXPENSE_AMOUNT DECIMAL(12, 0) NOT NULL COMMENT '총 결제 금액 (원)',
    PAYMENT_METHOD VARCHAR(50) DEFAULT 'CARD' COMMENT '결제 수단',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    FOREIGN KEY (GROUP_ID) REFERENCES TRIP_GROUP(GROUP_ID) ON DELETE CASCADE,
    FOREIGN KEY (PAYER_ID) REFERENCES MEMBER(MEMBER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='모임 지출 영수증 테이블';

-- 6. 지출 분할 대상자 테이블 (EXPENSE_PARTICIPANT)
CREATE TABLE EXPENSE_PARTICIPANT (
    PARTICIPANT_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '분담자 식별자',
    SETTLEMENT_ID INT NOT NULL COMMENT '영수증 ID',
    MEMBER_ID INT NOT NULL COMMENT '회원 ID',
    SPLIT_AMOUNT DECIMAL(12, 0) NOT NULL COMMENT '해당 인원의 분담액',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    FOREIGN KEY (SETTLEMENT_ID) REFERENCES EXPENSE_SETTLEMENT(SETTLEMENT_ID) ON DELETE CASCADE,
    FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER(MEMBER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='지출 N빵 분담 대상자 테이블';

-- 7. 여행 갤러리 테이블 (TRIP_GALLERY)
CREATE TABLE TRIP_GALLERY (
    GALLERY_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT '사진 고유 식별자',
    GROUP_ID INT NOT NULL COMMENT '모임 ID',
    UPLOADER_ID INT NOT NULL COMMENT '업로더 회원 ID',
    IMAGE_URL VARCHAR(255) NOT NULL COMMENT '사진 파일 경로 또는 이미지 URL',
    CAPTION VARCHAR(255) NULL COMMENT '사진 한 줄 캡션',
    LIKE_COUNT INT DEFAULT 0 COMMENT '좋아요 수',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    FOREIGN KEY (GROUP_ID) REFERENCES TRIP_GROUP(GROUP_ID) ON DELETE CASCADE,
    FOREIGN KEY (UPLOADER_ID) REFERENCES MEMBER(MEMBER_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='여행 추억 갤러리 테이블';

-- ==============================================================================
-- 8. COMMON_CODE_GROUP (공통 코드 그룹 테이블)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS COMMON_CODE_GROUP (
    GROUP_CODE VARCHAR(30) PRIMARY KEY COMMENT '코드 그룹 ID (예: TRIP_TYPE, MEMBER_ROLE)',
    GROUP_NAME VARCHAR(100) NOT NULL COMMENT '코드 그룹명',
    DESCRIPTION VARCHAR(255) NULL COMMENT '설명',
    IS_ACTIVE CHAR(1) DEFAULT 'Y' COMMENT '사용 여부 (Y/N)',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='공통 코드 그룹 관리 테이블';

-- ==============================================================================
-- 9. COMMON_CODE (공통 코드 상세 테이블)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS COMMON_CODE (
    CODE_ID VARCHAR(30) NOT NULL COMMENT '상세 코드 ID (예: DOMESTIC, OVERSEAS, LEADER)',
    GROUP_CODE VARCHAR(30) NOT NULL COMMENT '소속 코드 그룹 ID',
    CODE_NAME VARCHAR(100) NOT NULL COMMENT '코드명',
    SORT_ORDER INT DEFAULT 0 COMMENT '정렬 순서',
    IS_ACTIVE CHAR(1) DEFAULT 'Y' COMMENT '사용 여부 (Y/N)',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시',
    PRIMARY KEY (GROUP_CODE, CODE_ID),
    FOREIGN KEY (GROUP_CODE) REFERENCES COMMON_CODE_GROUP(GROUP_CODE) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='공통 코드 상세 관리 테이블';
